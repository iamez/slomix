TIMING_PEER = TIMING_PEER.replace(
    next(line for line in PEER.splitlines() if line.strip().startswith('raw = ')),
    "    raw = bytes.fromhex(config['stats_hex'])")
TIMING_PEER = TIMING_PEER.replace(
    next(line for line in PEER.splitlines() if line.strip().startswith('name = ')),
    "    name = config['stats_name']")


def capture_native_timing_pair(tmp_path, listener):  # noqa: F811
    server, path = listener
    authority, spool, pair, host, stats_capture = roots(tmp_path)
    timing_capture, fixture = tmp_path / 'captured-timing', tmp_path / 'lua-timing'
    timing_capture.mkdir(mode=0o700)
    fixture.mkdir(mode=0o700)
    stats_fixture = tmp_path / 'lua-stats'
    stats_fixture.mkdir(mode=0o700)
    stats_payloads = {}
    payloads = {}
    for half, identity in ((1, pair.first), (2, pair.second)):
        emitted = run_writer('lua5.4', stats_fixture, pair, half,
                             'bound-ipc' if half == 1 else 'bound-ipc-retry')
        stats_payloads[half] = emitted.filename, (emitted.root / emitted.generation / emitted.filename).read_bytes()
        run_timing(fixture, enabled=False, target=False, mode='frame', identity=identity)
        name = NAME.replace('R1', f'R{half}')
        payloads[half] = name, (fixture / name).read_bytes()
    executable = Path(sys.executable).resolve()
    with subprocess.Popen([str(executable), '-c', TIMING_PEER, str(path)],
                          stdin=subprocess.PIPE, stdout=subprocess.PIPE,
                          stderr=subprocess.PIPE, text=True, umask=0o077) as peer:
        try:
            assert peer.stdout.readline().strip() == 'READY'
            with pin_process(peer.pid, **approval(executable)) as pin:
                epoch = reserve_process_epoch(host, pin, source_id=pair.first.source_id)
                driver = RuntimeTimingController(authority=authority, host_authority=host,
                    producer_spool=spool, capture_root=stats_capture,
                    timing_capture_root=timing_capture,
                    timing_filenames={half: TimingFilenamePolicy('supply', half) for half in (1, 2)},
                    match_id=pair.first.match_id, source_id=pair.first.source_id,
                    map_name='supply', pin=pin, epoch=epoch)
                for half in (1, 2):
                    dispatch = driver.prepare_half()
                    name, payload = payloads[half]
                    peer.stdin.write(json.dumps(dict(generation=dispatch.generation,
                        directory=str(spool / dispatch.generation), timing_name=name,
                        timing_hex=payload.hex(), stats_name=stats_payloads[half][0],
                        stats_hex=stats_payloads[half][1].hex())) + '\n')
                    peer.stdin.flush()
                    connection, _ = server.accept()
                    driver.bootstrap(connection)
                    peer.stdin.write('finish\n')
                    peer.stdin.flush()
                    connection, _ = server.accept()
                    driver.complete(connection)
                    connection, _ = server.accept()
                    timing = driver.complete_timing(half, connection)
                    assert timing.sha256 == hashlib.sha256(payload).hexdigest()
                    assert driver.timing_status()[half] == 'captured'
                    peer.stdin.write('next\n')
                    peer.stdin.flush()
                handoff = driver.captured_timing_match()
                handoff.verify()
                assert handoff.stats.first_identity == pair.first
                assert handoff.timings[1].identity == pair.second
                for item in handoff.timings:
                    assert (item.root / item.generation / item.filename).read_bytes() == payloads[item.identity.round_number][1]
        finally:
            stdout, stderr = peer.communicate(timeout=5)
            assert peer.returncode == 0, stdout + stderr

    return handoff


def test_native_two_half_timing_controller_exports_bound_handoff(tmp_path, listener):  # noqa: F811
    capture_native_timing_pair(tmp_path, listener).verify()
